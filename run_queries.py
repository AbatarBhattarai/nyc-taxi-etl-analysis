"""
run_queries.py — Execute every query in queries.sql against nyc_taxi.db
and write the verified results to query-results.md.

Each query in queries.sql starts with a "-- Qn: title" header comment.
The numbers in query-results.md (and quoted in the README) come from
actually running these queries — nothing is typed in by hand.
"""

import re
import sqlite3

DB_PATH = "nyc_taxi.db"
SQL_PATH = "queries.sql"
OUT_PATH = "query-results.md"


def split_queries(sql_text):
    """Split queries.sql into (title, sql) pairs using the -- Qn: headers."""
    parts = re.split(r"--\s*(Q\d+:[^\n]*)", sql_text)
    queries = []
    for i in range(1, len(parts), 2):
        title = parts[i].strip()
        body = parts[i + 1]
        # Drop remaining comment lines, keep the SQL statement itself.
        sql_lines = [ln for ln in body.splitlines() if not ln.strip().startswith("--")]
        sql = "\n".join(sql_lines).strip().rstrip(";")
        if sql:
            queries.append((title, sql))
    return queries


def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        cells = []
        for v in r:
            if isinstance(v, float):
                cells.append(f"{v:,.2f}")
            elif isinstance(v, int):
                cells.append(f"{v:,}")
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def main():
    with open(SQL_PATH) as f:
        queries = split_queries(f.read())

    conn = sqlite3.connect(DB_PATH)
    lines = [
        "# Query Results — NYC Yellow Taxi, January 2025 (cleaned data)",
        "",
        "Generated by `run_queries.py` against `nyc_taxi.db` "
        "(3,226,518 cleaned trips). Every number below is actual query output.",
        "",
    ]
    for title, sql in queries:
        cur = conn.execute(sql)
        headers = [d[0] for d in cur.description]
        rows = cur.fetchall()
        lines.append(f"## {title}")
        lines.append("")
        lines.append(md_table(headers, rows))
        lines.append("")
        print(f"{title}: {len(rows)} rows")
    conn.close()

    with open(OUT_PATH, "w") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
